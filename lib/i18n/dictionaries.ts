const map: Record<Locale, Record<string, string>> = { tr, en };

export function getDictionary(locale: Locale): Record<string, string> {
  return map[locale] ?? tr;
}

export function translate(
  locale: Locale,
  key: string,
  fallback?: string
): string {
  const dict = getDictionary(locale);
  const trDict = getDictionary("tr");
  return dict[key] ?? trDict[key] ?? fallback ?? key;
}
